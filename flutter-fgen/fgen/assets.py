"""Asset constants ('fgen assets'): scan assets/, write a Dart constants file and list the folders in pubspec.yaml."""

from __future__ import annotations

import re
from pathlib import Path

from .jsonmodel import field_name
from .naming import Names, to_snake

GENERATED_MARK = "GENERATED by 'fgen assets'"
FONT_EXTENSIONS = {".ttf", ".otf", ".ttc"}  # fonts are declared under flutter: fonts:
_VARIANT_DIR = re.compile(r"^\d+(\.\d+)?x$")   # 2.0x / 3.0x resolution variants are picked up automatically


class AssetsError(Exception):
    pass


def scan(root: Path, assets_dir: str) -> list[str]:
    """Asset files (project-relative, posix) below `assets_dir`, without fonts, hidden files and resolution variants."""
    base = root / assets_dir
    if not base.is_dir():
        raise AssetsError(f"'{assets_dir}' was not found in {root}")
    files: list[str] = []
    for path in sorted(base.rglob("*")):
        if not path.is_file():
            continue
        rel = path.relative_to(root).as_posix()
        parts = path.relative_to(base).parts
        if any(p.startswith(".") for p in parts) or any(_VARIANT_DIR.match(p) for p in parts[:-1]):
            continue
        if path.suffix.lower() in FONT_EXTENSIONS or path.name.lower() in ("thumbs.db", "desktop.ini"):
            continue
        files.append(rel)
    return files


def folders(files: list[str]) -> list[str]:
    out: list[str] = []
    for rel in files:
        folder = rel.rsplit("/", 1)[0] + "/"
        if folder not in out:
            out.append(folder)
    return sorted(out)


def group_constants(files: list[str], assets_dir: str) -> dict[str, list[tuple[str, str]]]:
    """{class name: [(constant, path)]}: one class per top-level folder (assets/images -> AppImages)."""
    prefix = assets_dir.strip("/") + "/"
    grouped: dict[str, list[tuple[str, str]]] = {}
    for rel in files:
        parts = rel[len(prefix):].split("/")
        group = "AppAssets"
        if len(parts) > 1:
            words = to_snake(re.sub(r"[^A-Za-z0-9]+", " ", parts[0]))
            group = "App" + Names(words).pascal if words else "AppAssets"
            parts = parts[1:]
        grouped.setdefault(group, []).append(("/".join(parts), rel))

    out: dict[str, list[tuple[str, str]]] = {}
    for group, items in grouped.items():
        stems = [re.sub(r"\.[^./]+$", "", inner) for inner, _ in items]
        clashing = {s for s in stems if stems.count(s) > 1}  # logo.png + logo.svg -> logoPng, logoSvg
        taken: set[str] = set()
        constants = []
        for (inner, rel), stem in zip(items, stems):
            key = inner if stem in clashing else stem
            name = field_name(key, taken)
            if name.startswith("n") and key[:1].isdigit():  # '404.png' -> asset404, not n404
                name = "asset" + name[1:]
            constants.append((name, rel))
        out[group] = constants
    return dict(sorted(out.items(), key=lambda kv: (kv[0] != "AppAssets", kv[0])))


def render(groups: dict[str, list[tuple[str, str]]]) -> str:
    blocks = [f"// {GENERATED_MARK}. Do not edit by hand: add files under assets/ and run it again."]
    for group, constants in groups.items():
        lines = [f"abstract final class {group} {{"]
        lines += [f"  static const {name} = '{path}';" for name, path in constants]
        lines.append("}")
        blocks.append("\n".join(lines))
    return "\n\n".join(blocks) + "\n"


# --------------------------------------------------------------------------- pubspec
def add_to_pubspec(text: str, entries: list[str]) -> tuple[str, list[str]]:
    """Add the missing `entries` to `flutter: assets:`. Returns (new text, added entries)."""
    lines = text.split("\n")
    start = next((i for i, line in enumerate(lines) if re.match(r"^flutter:\s*(#.*)?$", line)), None)
    if start is None:
        body = ["", "flutter:", "  assets:", *(f"    - {e}" for e in entries)]
        return text.rstrip("\n") + "\n" + "\n".join(body) + "\n", list(entries)

    end = len(lines)
    for i in range(start + 1, len(lines)):
        if lines[i] and not lines[i][0].isspace() and not lines[i].startswith("#"):
            end = i
            break

    key = None
    for i in range(start + 1, end):
        m = re.match(r"^(\s+)assets:\s*(.*?)\s*$", lines[i])
        if m:
            if m.group(2) and not m.group(2).startswith("#"):
                raise AssetsError("pubspec.yaml uses an inline 'assets:' list; change it to one '- path' per line first")
            key = (i, len(m.group(1)))
            break

    if key is None:
        child = next((len(l) - len(l.lstrip()) for l in lines[start + 1:end] if l.strip() and not l.lstrip().startswith("#")), 2)
        pad = " " * child
        block = [f"{pad}assets:", *(f"{pad}  - {e}" for e in entries)]
        return "\n".join(lines[: start + 1] + block + lines[start + 1:]), list(entries)

    index, indent = key
    existing: set[str] = set()
    last = index
    item_indent = indent + 2
    for i in range(index + 1, end):
        stripped = lines[i].strip()
        if not stripped or stripped.startswith("#"):
            continue
        current = len(lines[i]) - len(lines[i].lstrip())
        if not stripped.startswith("-") or current < indent:
            break
        item_indent = current
        existing.add(stripped[1:].split("#")[0].strip().strip("'\"").rstrip("/") + "/")
        existing.add(stripped[1:].split("#")[0].strip().strip("'\""))
        last = i
    added = [e for e in entries if e not in existing]
    new = [f"{' ' * item_indent}- {e}" for e in added]
    return "\n".join(lines[: last + 1] + new + lines[last + 1:]), added
